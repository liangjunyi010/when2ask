"""Check Team 11's rubric, numerical evidence, editable diagram and playback."""
import hashlib
import io
import json
from pathlib import Path
import re
from xml.etree import ElementTree as ET
from zipfile import ZipFile
from PIL import Image
BASE=Path(__file__).resolve().parents[1]
ROOT=BASE.parents[1]
N={'p':'http://schemas.openxmlformats.org/presentationml/2006/main',
   'a':'http://schemas.openxmlformats.org/drawingml/2006/main',
   'c':'http://schemas.openxmlformats.org/drawingml/2006/chart'}
j=lambda p:json.loads(p.read_text())
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
def txt(e):return ' '.join(x.text or ''for x in e.findall('.//a:t',N))
def rows(e):return [[txt(c)for c in r.findall('a:tc',N)]for r in e.findall('.//a:tbl/a:tr',N)]

def main():
    deck=BASE/'deliverables/When2Ask_Team11_Final_Presentation.pptx'
    script=j(BASE/'speaker_script.json');flow=j(BASE/'flow_spec.json')
    data=j(ROOT/'presentation/final_benchmark_cost/analysis/cost_report.json')
    assert script['team_number']==11 and script['members']==['Liang Junyi','Yang Haocheng']
    assert len(script['slides'])==10 and sum(s['target_seconds']for s in script['slides'])==570
    assert 'As we learned in class' in script['slides'][1]['script']
    assert all(word in script['slides'][1]['script']for word in ['zero-shot','response speed','inference cost'])
    wpm=[s['spoken_words']*60/(s['target_seconds']-(22.2 if s['slide']==9 else 0))for s in script['slides']]
    assert max(wpm)<126
    for f in data['input_files']:assert sha(ROOT/f['path'])==f['sha256']
    assert [m['successes']for m in data['methods']]==[10,12,12]
    ids={n['id']for n in flow['nodes']}
    assert len(ids)==9 and len(flow['edges'])==10
    edges={e['id']:(e['from'],e['to'])for e in flow['edges']}
    assert edges['ask']==('gate','question-planner')
    assert edges['continue']==('gate','action-planner')
    assert edges['done']==('action-planner','evaluator')
    assert edges['history-state']==('history','public-state')and edges['observation-state']==('observation','public-state')
    assert {e['to']for e in flow['edges']if e['from']=='gate'}=={'question-planner','action-planner'}
    # Every segment avoids unrelated node interiors. This detects a real diagram
    # routing error rather than merely asserting the intended labels exist.
    for edge in flow['edges']:
        for (x1,y1),(x2,y2)in zip(edge['points'],edge['points'][1:]):
            assert x1==x2 or y1==y2
            for n in flow['nodes']:
                if n['id']in [edge['from'],edge['to']]:continue
                l,r,t,b=n['x'],n['x']+n['width'],n['y'],n['y']+n['height']
                hit=(x1==x2 and l<x1<r and max(min(y1,y2),t)<min(max(y1,y2),b))or(y1==y2 and t<y1<b and max(min(x1,x2),l)<min(max(x1,x2),r))
                assert not hit,(edge['id'],n['id'])
    with ZipFile(deck)as z:
        assert z.testzip()is None
        pres=ET.fromstring(z.read('ppt/presentation.xml'))
        assert len(pres.findall('p:sldIdLst/p:sldId',N))==10
        size=pres.find('p:sldSz',N);assert (int(size.get('cx')),int(size.get('cy')))==(15240000,8572500)
        slides=[ET.fromstring(z.read(f'ppt/slides/slide{i}.xml'))for i in range(1,11)]
        assert all(x in txt(slides[0])for x in ['Team 11','Liang Junyi','Yang Haocheng'])
        assert all(x in txt(slides[1])for x in ['Problem & Motivation','zero-shot','latency','inference cost'])
        for i,s in enumerate(slides):
            assert not re.search(r'\bsource\s*:|generated by|/Users/|outputs/|\.json\b',txt(s),re.I)
            notes=ET.fromstring(z.read(f'ppt/notesSlides/notesSlide{i+1}.xml'))
            assert ' '.join(script['slides'][i]['script'].split())in' '.join(txt(notes).split())
        # The actual editable connectors, their endpoints and arrow direction
        # must match the diagram specification, not just a screenshot.
        actual={q.find('p:nvCxnSpPr/p:cNvPr',N).get('name'):q for q in slides[2].findall('.//p:cxnSp',N)}
        assert len(actual)==sum(len(e['points'])-1 for e in flow['edges'])==17
        for edge in flow['edges']:
            for i,(start,end)in enumerate(zip(edge['points'],edge['points'][1:]),1):
                q=actual[f"{edge['id']}-{i}"]
                f=q.find('p:spPr/a:xfrm',N);off=f.find('a:off',N);ext=f.find('a:ext',N)
                expected=[min(start[0],end[0]),min(start[1],end[1]),abs(end[0]-start[0]),abs(end[1]-start[1])]
                observed=[int(off.get('x'))/9525,int(off.get('y'))/9525,int(ext.get('cx'))/9525,int(ext.get('cy'))/9525]
                assert all(abs(a-b)<.001 for a,b in zip(expected,observed))
                assert (f.get('flipH')=='1')==(end[0]<start[0])
                assert (f.get('flipV')=='1')==(end[1]<start[1])
                tail=q.find('p:spPr/a:ln/a:tailEnd',N)
                if i==len(edge['points'])-1:assert tail is not None and tail.get('type')=='triangle'
        assert rows(slides[4])[1:]==[['Development','6','24','0 / 1 (balanced)'],['Held-out Test','12','12','0 / 1 (balanced)']]
        assert rows(slides[6])[1:]==[[n,f"{m['mean_burden']:.3f}"]for n,m in zip(['NoAsk','LLM-Gate','Jev-Gate'],data['methods'])]
        assert rows(slides[7])[1:]==[[n,f"{m['api_latency_s']:.2f} s",f"${m['estimated_total_usd']:.4f}"]for n,m in zip(['NoAsk','LLM-Gate','Jev-Gate'],data['methods'])]
        assert all(s in txt(slides[7])for s in ['Estimates, not invoices.','Different trajectories.','NoAsk remains fastest and cheapest overall.'])
        charts=[ET.fromstring(z.read(n))for n in z.namelist()if re.fullmatch(r'ppt/(?:slides/)?charts/chart\d+.xml',n)]
        assert len(charts)==2
        values=[[float(x.text)for x in c.findall('.//c:val//c:pt/c:v',N)]for c in charts]
        assert any(len(v)==3 and all(abs(a-b)<1e-12 for a,b in zip(v,[10/12,1,1]))for v in values)
        means=[next(s['mean_latency_ms']for s in data['stages']if s['stage']=='gate'and s['method']==m)for m in ['llm_gate','jev_gate']]
        assert any(len(v)==2 and all(abs(a-b)<1e-10 for a,b in zip(v,means))for v in values)
        assert len([n for n in z.namelist()if n.startswith('ppt/embeddings/')and n.endswith('.xlsx')])==2
        assert len(slides[8].findall('.//a:videoFile',N))==1
        assert slides[8].find('.//p:cmd[@cmd="playFrom(0.0)"]',N)is not None
        for ext in ['gif','mp4']:assert z.read('ppt/media/when2ask_highlight.'+ext)==(ROOT/f'presentation/final_benchmark/media/when2ask_highlight.{ext}').read_bytes()
        gif=Image.open(io.BytesIO(z.read('ppt/media/when2ask_highlight.gif')));assert gif.n_frames==164
    native=j(BASE/'native_powerpoint_validation.json')
    assert native['pptx_sha256']==sha(deck)and native['autoplay_verified']
    for i in range(1,11):assert Image.open(BASE/f'slide_previews/powerpoint-compatible-{i:02d}.png').size==(1600,900)
    snapshot=ROOT/'outputs/local_console/team11-presentation-protection-20261112.json'
    protected=j(snapshot)['files']if snapshot.exists()else j(BASE/'checks/protected_artifacts.json')['files']
    changed=[f['path']for f in protected if sha(ROOT/f['path'])!=f['sha256']]
    assert not changed,changed
    receipt=j(BASE/'.build/finalization-v1.json')if (BASE/'.build/finalization-v1.json').exists()else j(BASE/'checks/pptx_finalization.json')
    assert receipt['finalSha256']==sha(deck)
    result=dict(passed=True,pptx_sha256=sha(deck),slides=10,aspect='16:9',team_number=11,members=script['members'],
                lecture_connection_in_script=True,visible_zero_shot_latency_cost=True,native_flow_nodes=9,
                native_connector_segments=17,flow_routes_avoid_unrelated_nodes=True,gate_cannot_output_done=True,
                loop_returns_to_public_state=True,editable_tables=[5,7,8],editable_charts=[7,8],
                speaker_notes_match=True,script_words=sum(s['spoken_words']for s in script['slides']),
                scheduled_seconds=570,replay_seconds=22.2,per_slide_wpm=[round(x,1)for x in wpm],
                embedded_video_native_autoplay_verified=True,original_files_unchanged=len(protected),new_model_api_calls=0)
    (BASE/'presentation_validation.json').write_text(json.dumps(result,indent=2)+'\n')
    (BASE/'checks/pptx_finalization.json').write_text(json.dumps(receipt,indent=2)+'\n')
    (BASE/'rubric_coverage.json').write_text(json.dumps({'title_slide':{'team':11,'members':script['members']},
        'problem_and_motivation':[2],'approach_and_implementation':[3,4,5,6],
        'results_and_demonstration':[7,8,9],'discussion_and_conclusions':[10],
        'presentation_seconds':570,'buffer_seconds':30},indent=2)+'\n')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
