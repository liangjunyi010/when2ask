"""Validate the final presentation against preserved raw Test evidence."""
from __future__ import annotations
import hashlib
import io
import json
from pathlib import Path
import re
from xml.etree import ElementTree as ET
from zipfile import ZipFile
from PIL import Image

BASE=Path(__file__).resolve().parents[1]
ROOT=BASE.parents[1]
NS={'p':'http://schemas.openxmlformats.org/presentationml/2006/main',
    'a':'http://schemas.openxmlformats.org/drawingml/2006/main',
    'c':'http://schemas.openxmlformats.org/drawingml/2006/chart'}
load=lambda p:json.loads(p.read_text())
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
def texts(e):return ' '.join(x.text or ''for x in e.findall('.//a:t',NS))
def rows(e):return [[texts(c)for c in r.findall('a:tc',NS)]for r in e.findall('.//a:tbl/a:tr',NS)]

def main():
    deck=BASE/'deliverables/When2Ask_Benchmark_Presentation_v2.pptx'
    report=load(BASE/'analysis/cost_report.json')
    script=load(BASE/'speaker_script.json')
    assert len(script['slides'])==10 and sum(x['target_seconds']for x in script['slides'])==580
    words=sum(x['spoken_words']for x in script['slides'])
    assert words==1091
    # Allow the entire unchanged clip as a separate hold, not invisible extra time.
    effective_wpm=[s['spoken_words']*60/(s['target_seconds']-(22.2 if s['slide']==9 else 0))for s in script['slides']]
    assert max(effective_wpm)<125
    for f in report['input_files']:assert sha(ROOT/f['path'])==f['sha256']
    portable_protection=load(BASE/'analysis/protected_artifacts.json')['files']
    for f in portable_protection:assert sha(ROOT/f['path'])==f['sha256']
    assert report['new_model_api_calls']==0
    assert sum(m['api_attempts']for m in report['methods'])==262
    assert [m['successes']for m in report['methods']]==[10,12,12]
    for m in report['methods']:
        assert abs(m['estimated_total_usd']-(m['estimated_deepseek_usd']+(m['estimated_jev_usd']or 0)))<1e-12
    assert abs(report['comparisons']['estimated_total_usd_reduction_fraction']-.03723541024191557)<1e-12
    with ZipFile(deck)as z:
        assert z.testzip()is None
        p=ET.fromstring(z.read('ppt/presentation.xml'))
        assert len(p.findall('p:sldIdLst/p:sldId',NS))==10
        size=p.find('p:sldSz',NS)
        assert (int(size.get('cx')),int(size.get('cy')))==(15240000,8572500)
        slides=[ET.fromstring(z.read(f'ppt/slides/slide{i}.xml'))for i in range(1,11)]
        for i,s in enumerate(slides):
            text=texts(s)
            assert not re.search(r'\bsource\s*:|generated by|/Users/|outputs/|\.json\b',text,re.I),text
            notes=ET.fromstring(z.read(f'ppt/notesSlides/notesSlide{i+1}.xml'))
            assert ' '.join(script['slides'][i]['script'].split())in' '.join(texts(notes).split())
            assert script['slides'][i]['evidence'] in texts(notes)
        assert rows(slides[3])[1:]==[['Development','6','24','0 / 1 (balanced)'],['Held-out Test','12','12','0 / 1 (balanced)']]
        labels=['NoAsk','LLM-Gate','Jev-Gate']
        assert rows(slides[6])[1:]==[[labels[i],f"{m['mean_burden']:.3f}",f"{m['api_latency_s']:.2f} s"]for i,m in enumerate(report['methods'])]
        assert rows(slides[7])[1:]==[[labels[i],f"${m['estimated_deepseek_usd']:.4f}",'—'if m['estimated_jev_usd']is None else f"${m['estimated_jev_usd']:.4f}",f"${m['estimated_total_usd']:.4f}"]for i,m in enumerate(report['methods'])]
        assert 'Estimates, not invoices.'in texts(slides[7])
        assert '53 LLM calls; 54 Jev calls. Different trajectories.'in texts(slides[7])
        assert 'NoAsk remains fastest and cheapest overall.'in texts(slides[7])
        assert 'Report measured code'in texts(slides[2])
        charts=[ET.fromstring(z.read(n))for n in z.namelist()if re.fullmatch(r'ppt/(?:slides/)?charts/chart\d+.xml',n)]
        assert len(charts)==2
        observed=[[float(x.text)for x in c.findall('.//c:val//c:pt/c:v',NS)]for c in charts]
        assert any(len(vals)==3 and all(abs(v-t)<1e-14 for v,t in zip(vals,[10/12,1,1]))for vals in observed)
        gate_means=[next(s['mean_latency_ms']for s in report['stages']if s['method']==m and s['stage']=='gate')for m in ['llm_gate','jev_gate']]
        assert any(len(vals)==2 and all(abs(v-t)<1e-10 for v,t in zip(vals,gate_means))for vals in observed)
        assert len([n for n in z.namelist()if n.startswith('ppt/embeddings/')and n.endswith('.xlsx')])==2
        assert len(slides[8].findall('.//a:videoFile',NS))==1
        assert slides[8].find('.//p:cmd[@cmd="playFrom(0.0)"]',NS)is not None
        for ext in ['mp4','gif']:
            assert z.read('ppt/media/when2ask_highlight.'+ext)==(BASE.parent/'final_benchmark'/('media/when2ask_highlight.'+ext)).read_bytes()
        gif=Image.open(io.BytesIO(z.read('ppt/media/when2ask_highlight.gif')))
        assert gif.n_frames==164
        for n in z.namelist():
            if re.fullmatch(r'ppt/media/image\d*\.png',n):
                assert len(z.read(n))>1000 and Image.open(io.BytesIO(z.read(n))).width>100
    native=load(BASE/'native_powerpoint_validation.json')
    assert native['pptx_sha256']==sha(deck)and native['slides']==10 and native['autoplay_verified']
    for i in range(1,11):
        assert Image.open(BASE/f'slide_previews/slide-{i}.png').size==(1600,900)
        assert Image.open(BASE/f'slide_previews/powerpoint-compatible-{i:02d}.png').size==(1600,900)
    snapshot=ROOT/'outputs/local_console/presentation-cost-protection-20261112.json'
    protection=load(snapshot)if snapshot.exists()else {'files':portable_protection}
    changed=[x['path']for x in protection['files']if sha(ROOT/x['path'])!=x['sha256']]
    assert changed==[],changed
    receipt=load(BASE/'.build/finalization-v3.json')
    assert receipt['finalSha256']==sha(deck)
    result=dict(passed=True,pptx_sha256=sha(deck),slide_count=10,aspect='16:9',
                editable_table_slides=[4,7,8],editable_chart_slides=[7,8],embedded_workbooks=2,
                raw_test_episodes=36,actual_saved_attempts=262,new_model_api_calls=0,
                original_tracked_files_unchanged=len(protection['files']),original_dirty_milestone_preserved=True,
                original_benchmark_reports_and_configs_unchanged=True,
                estimated_usd_only=True,cache_hit_miss_usage_verified=True,
                current_rates_verified_date=report['pricing_assumptions']['verified_date'],
                source_request_time_range=report['request_time_range_utc'],
                speaker_notes_and_visible_tables_match=True,script_words=words,target_seconds=580,
                replay_duration_s=22.2,replay_frame_count=164,embedded_video_native_autoplay_verified=True,
                per_slide_wpm_with_separate_replay=[round(v,1)for v in effective_wpm],
                visible_source_labels=False)
    (BASE/'presentation_validation.json').write_text(json.dumps(result,indent=2)+'\n')
    (BASE/'checks/pptx_finalization.json').write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
