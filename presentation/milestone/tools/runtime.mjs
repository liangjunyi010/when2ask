import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
export const ROOT=fileURLToPath(new URL('../../../',import.meta.url));
export const BASE=path.join(ROOT,'presentation/milestone');
export const BUILD=path.join(BASE,'.build');
export const RUNTIME=process.env.WHEN2ASK_RUNTIME_MODULES||path.join(os.homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
process.env.RUNTIME_NODE_MODULES ||= RUNTIME;
fs.mkdirSync(BUILD,{recursive:true});
if(!fs.existsSync(path.join(BUILD,'node_modules')))fs.symlinkSync(RUNTIME,path.join(BUILD,'node_modules'),'dir');
export const requireRuntime=createRequire(path.join(BUILD,'runtime.cjs'));
