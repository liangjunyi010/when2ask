"""Verify delivered presentation claims and media against raw saved episodes."""
from __future__ import annotations
import hashlib
import io
import json
from pathlib import Path
import re
from xml.etree import ElementTree as ET
from zipfile import ZipFile
from PIL import Image
BASE=Path(__file__).resolve().parents[1]
ROOT=BASE.parents[1]
NS={'p':'http://schemas.openxmlformats.org/presentationml/2006/main','a':'http://schemas.openxmlformats.org/drawingml/2006/main','c':'http://schemas.openxmlformats.org/drawingml/2006/chart'}
def j(p):return json.loads(p.read_text())
def texts(e):return ' '.join(x.text or '' for x in e.findall('.//a:t',NS))
def rows(e):return [[texts(c)for c in r.findall('a:tc',NS)]for r in e.findall('.//a:tbl/a:tr',NS)]
deck=BASE/'deliverables/When2Ask_Benchmark_Presentation.pptx'
summary=j(ROOT/'outputs/three_task_v8/report/summary.json')
script=j(BASE/'speaker_script.json')
assert len(script['slides'])==9
with ZipFile(deck)as z:
 assert z.testzip()is None
 for n in z.namelist():
  if re.fullmatch(r'ppt/media/image\d*\.png',n):
   assert len(z.read(n))>1000,n
   assert Image.open(io.BytesIO(z.read(n))).size[0]>100,n
 p=ET.fromstring(z.read('ppt/presentation.xml'))
 assert len(p.findall('p:sldIdLst/p:sldId',NS))==9
 size=p.find('p:sldSz',NS);assert (int(size.get('cx')),int(size.get('cy')))==(15240000,8572500)
 slides=[ET.fromstring(z.read(f'ppt/slides/slide{i}.xml'))for i in range(1,10)]
 inspection=next(json.loads(x) for x in (ROOT/'data/three_task_v8/r2/test.jsonl').read_text().splitlines()
                 if json.loads(x)['template_id']=='occlusion_inspection')
 assert inspection['dag']['nodes']==['clear_screen','inspect_label','report_code']
 assert 'Report measured code' in texts(slides[2]) and 'Report → restore' not in texts(slides[2])
 for i,s in enumerate(slides):
  text=texts(s)
  assert not re.search(r'\bsource\s*:|generated by|/Users/|outputs/|\.json\b',text,re.I),text
  note=ET.fromstring(z.read(f'ppt/notesSlides/notesSlide{i+1}.xml'))
  assert ' '.join(script['slides'][i]['script'].split())in' '.join(texts(note).split())
 assert rows(slides[3])[1:]==[['Development','6','24','0 / 1 (balanced)'],['Held-out Test','12','12','0 / 1 (balanced)']]
 actual=[]
 for m in summary['methods']:
  episodes=[j(p)for p in (ROOT/'outputs/three_task_v8/test_runs').glob('*__'+m['method']+'/episode.json')]
  assert len(episodes)==12 and len({e['group_id']for e in episodes})==12
  assert sum(e['evaluation']['task_success']for e in episodes)==m['successes']
  burden=sum(e['evaluation']['clarification_burden']for e in episodes)/12
  latency=sum(e['cost']['api_latency_ms']for e in episodes)/1000
  assert abs(latency-m['api_latency_s'])<1e-6
  actual.append([{'llm_noask':'NoAsk','llm_gate':'LLM-Gate','jev_gate':'Jev-Gate'}[m['method']],f'{burden:.3f}',f'{latency:.2f} s'])
 assert rows(slides[6])[1:]==actual
 charts=[n for n in z.namelist()if re.fullmatch(r'ppt/(?:slides/)?charts/chart\d+.xml',n)]
 assert len(charts)==1
 chart=ET.fromstring(z.read(charts[0]));vals=[float(x.text)for x in chart.findall('.//c:val//c:pt/c:v',NS)]
 assert len(vals)==3 and all(abs(v-m['success_rate'])<1e-14 for v,m in zip(vals,summary['methods']))
 assert any(n.startswith('ppt/embeddings/')and n.endswith('.xlsx')for n in z.namelist())
 assert len(slides[7].findall('.//a:videoFile',NS))==1
 assert slides[7].find('.//p:cmd[@cmd="playFrom(0.0)"]',NS)is not None
 for ext in ['mp4','gif']:assert z.read('ppt/media/when2ask_highlight.'+ext)==(BASE/('media/when2ask_highlight.'+ext)).read_bytes()
 gif=Image.open(io.BytesIO(z.read('ppt/media/when2ask_highlight.gif')));assert gif.n_frames==164
for a in j(BASE/'evidence_manifest.json')['protected_artifacts']:
 assert hashlib.sha256((ROOT/a['path']).read_bytes()).hexdigest()==a['sha256']
for partition,n,groups in [('dev',24,6),('test',12,12)]:
 data=[json.loads(x)for x in (ROOT/f'data/three_task_v8/r2/{partition}.jsonl').read_text().splitlines()]
 assert len(data)==n and len({x['group_id']for x in data})==groups
browser=j(BASE/'browser_validation.json');assert browser['rendered_frames']==164 and browser['errors']==[]
assert all(browser[k]for k in ['pause','seek','restart'])
for i in range(1,10):assert Image.open(BASE/f'slide_previews/slide-{i}.png').size==(1600,900)
result=dict(passed=True,slide_count=9,aspect='16:9',pptx_sha256=hashlib.sha256(deck.read_bytes()).hexdigest(),
 editable_table_slides=[4,7],editable_chart_slides=[7],embedded_workbook=True,embedded_mp4_byte_identical=True,
 embedded_animated_gif_frames=gif.n_frames,speaker_notes_verified=True,visible_source_labels=False,
 raw_episodes_verified=36,methods_table=actual,protected_hashes_unchanged=True,
 timeline_frames_verified=164,script_words=sum(x['spoken_words']for x in script['slides']),
 target_seconds=sum(x['target_seconds']for x in script['slides']),new_model_api_calls=0)
(BASE/'presentation_validation.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps(result))
